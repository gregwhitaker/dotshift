// Package litellm turns a dotshift config into a LiteLLM proxy config.
package litellm

import (
	"fmt"

	"gopkg.in/yaml.v3"

	"github.com/gregwhitaker/dotshift/internal/config"
)

// ContainerConfigPath is where the generated config is mounted in the container.
const ContainerConfigPath = "/app/config.yaml"

// ContainerPort is the port the proxy listens on inside the container.
const ContainerPort = 4000

// Document is the subset of LiteLLM's proxy config that dotshift writes.
type Document struct {
	ModelList       []Deployment    `yaml:"model_list"`
	LiteLLMSettings LiteLLMSettings `yaml:"litellm_settings"`
}

// Deployment is one entry in LiteLLM's model_list.
type Deployment struct {
	ModelName     string        `yaml:"model_name"`
	LiteLLMParams LiteLLMParams `yaml:"litellm_params"`
}

// LiteLLMParams are the provider call settings for a deployment.
type LiteLLMParams struct {
	Model   string `yaml:"model"`
	APIKey  string `yaml:"api_key,omitempty"`
	APIBase string `yaml:"api_base,omitempty"`
}

// LiteLLMSettings holds proxy-wide behaviour.
type LiteLLMSettings struct {
	// Fallbacks maps a model name to the model names tried after it fails.
	Fallbacks  []map[string][]string `yaml:"fallbacks,omitempty"`
	DropParams bool                  `yaml:"drop_params"`
}

// FallbackName is the model name given to the nth model (1-based) after an
// alias's primary, e.g. "smart~1". Clients normally only call the alias.
func FallbackName(alias string, n int) string {
	return fmt.Sprintf("%s~%d", alias, n)
}

// Build converts a validated dotshift config into a LiteLLM document.
// Secrets are referenced as os.environ/NAME so their values never land in
// the generated file. The master key reaches the proxy as the
// LITELLM_MASTER_KEY environment variable instead (see package router).
func Build(c *config.Config) Document {
	doc := Document{LiteLLMSettings: LiteLLMSettings{DropParams: true}}
	for _, alias := range c.AliasNames() {
		models := c.Aliases[alias]
		var fallbacks []string
		for i, m := range models {
			name := alias
			if i > 0 {
				name = FallbackName(alias, i)
				fallbacks = append(fallbacks, name)
			}
			doc.ModelList = append(doc.ModelList, Deployment{ModelName: name, LiteLLMParams: params(c, m)})
		}
		if len(fallbacks) > 0 {
			doc.LiteLLMSettings.Fallbacks = append(doc.LiteLLMSettings.Fallbacks, map[string][]string{alias: fallbacks})
		}
	}
	return doc
}

func params(c *config.Config, model string) LiteLLMParams {
	provider, _, _ := config.SplitModel(model)
	p := c.Providers[provider]
	out := LiteLLMParams{Model: model, APIBase: p.BaseURL}
	if p.APIKeyEnv != "" {
		out.APIKey = envRef(p.APIKeyEnv)
	}
	return out
}

func envRef(name string) string { return "os.environ/" + name }

// Marshal renders the document as YAML with a header noting it is generated.
func Marshal(doc Document) ([]byte, error) {
	body, err := yaml.Marshal(doc)
	if err != nil {
		return nil, err
	}
	header := "# Generated by dotshift from dotshift.yaml. Do not edit; changes are overwritten.\n"
	return append([]byte(header), body...), nil
}
