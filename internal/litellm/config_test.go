package litellm

import (
	"reflect"
	"strings"
	"testing"

	"github.com/gregwhitaker/dotshift/internal/config"
)

const testConfig = `
router:
  master_key_env: DOTSHIFT_MASTER_KEY
providers:
  anthropic: {api_key_env: ANTHROPIC_API_KEY}
  openai: {api_key_env: OPENAI_API_KEY}
  ollama_chat: {base_url: "http://host.docker.internal:11434"}
aliases:
  smart: [anthropic/claude-sonnet-5-5, openai/gpt-5]
  local: [ollama_chat/qwen2.5-coder]
`

func TestBuild(t *testing.T) {
	c, err := config.Parse([]byte(testConfig))
	if err != nil {
		t.Fatal(err)
	}
	doc := Build(c)

	want := []Deployment{
		{ModelName: "local", LiteLLMParams: LiteLLMParams{Model: "ollama_chat/qwen2.5-coder", APIBase: "http://host.docker.internal:11434"}},
		{ModelName: "smart", LiteLLMParams: LiteLLMParams{Model: "anthropic/claude-sonnet-5-5", APIKey: "os.environ/ANTHROPIC_API_KEY"}},
		{ModelName: "smart~1", LiteLLMParams: LiteLLMParams{Model: "openai/gpt-5", APIKey: "os.environ/OPENAI_API_KEY"}},
	}
	if !reflect.DeepEqual(doc.ModelList, want) {
		t.Errorf("model_list =\n%+v\nwant\n%+v", doc.ModelList, want)
	}
	if got := doc.LiteLLMSettings.Callbacks; !reflect.DeepEqual(got, []string{"generic_api"}) || !doc.LiteLLMSettings.TurnOffMessageLogging {
		t.Errorf("usage callback = %v, turn_off_message_logging = %v", got, doc.LiteLLMSettings.TurnOffMessageLogging)
	}
	wantFallbacks := []map[string][]string{{"smart": {"smart~1"}}}
	if !reflect.DeepEqual(doc.LiteLLMSettings.Fallbacks, wantFallbacks) {
		t.Errorf("fallbacks = %v, want %v", doc.LiteLLMSettings.Fallbacks, wantFallbacks)
	}
}

func TestMarshalHasNoSecretsAndHeader(t *testing.T) {
	t.Setenv("ANTHROPIC_API_KEY", "sk-should-not-appear")
	c, err := config.Parse([]byte(testConfig))
	if err != nil {
		t.Fatal(err)
	}
	out, err := Marshal(Build(c))
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	if strings.Contains(s, "sk-should-not-appear") {
		t.Error("secret value written to generated config")
	}
	if !strings.HasPrefix(s, "# Generated by dotshift") {
		t.Error("missing generated header")
	}
	for _, want := range []string{"model_list:", "model_name: smart", "fallbacks:", "drop_params: true"} {
		if !strings.Contains(s, want) {
			t.Errorf("generated config missing %q:\n%s", want, s)
		}
	}
}

func TestBuildUsageOff(t *testing.T) {
	c, err := config.Parse([]byte(testConfig + "\n"))
	if err != nil {
		t.Fatal(err)
	}
	c.Router.UsageListen = config.UsageOff
	if doc := Build(c); doc.LiteLLMSettings.Callbacks != nil {
		t.Errorf("callbacks = %v with usage off", doc.LiteLLMSettings.Callbacks)
	}
}
